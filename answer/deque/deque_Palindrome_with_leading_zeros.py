import sys
from collections import deque

# 【方針】
# 先頭に '0' を追加して回文にできるということは、
# 最初から末尾にある連続した '0' を無視（削除）してしまえば、
# 残った文字列が回文になっているかどうかを判定するだけで済みます。

# 1. 入力と前処理
# rstrip('0') を使って、文字列の右側（末尾）にある '0' をすべて削除します。
# その後、list() で1文字ずつのリストに変換し、deque（デック）に渡します。
N = list(input().rstrip('0')) 
d = deque(N)

# 2. 回文判定（両端から削っていく）
# 要素が2つ以上ある間、両端から取り出して比較を続けます。
while len(d) > 1:
    right = d.pop()       # 右端（末尾）の文字を取り出す (O(1)で高速)
    left = d.popleft()    # 左端（先頭）の文字を取り出す (O(1)で高速)

    # もし両端の文字が一致しなければ、その時点で回文ではない
    if left != right:
        print("No")
        sys.exit()  # プログラムを強制終了

# 3. 終了処理 (while-else文)
# whileループが一度も sys.exit() で中断されずに最後まで回りきった場合、
# つまり「すべての両端チェックをクリアした」または「最初から1文字以下だった」場合に
# この else ブロックが実行されます。
else:
    print('Yes')