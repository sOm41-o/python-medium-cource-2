from math import factorial

# 【方針】
# 使える硬貨の中で「一番金額の大きいもの」から順に、使えるだけ使っていくのが最も枚数を減らす方法です。
# このような「その場その場での最善手（一番大きい硬貨を使う）」を繰り返して答えを出す手法を「貪欲法」と呼びます。

p = int(input())
answer = 0

# 10! 円硬貨から 1! 円硬貨まで、大きい順に調べていく
# range(10, 0, -1) は [10, 9, 8, ..., 1] というカウントダウンのリストを作ります
for i in range(10, 0, -1):
    
    # 現在見ている i! 円硬貨が、残りの支払い金額 p 以下の間は使い続ける
    while p >= factorial(i):
        p -= factorial(i)  # i! 円支払う
        answer += 1        # 使った硬貨の枚数を1増やす

print(answer)